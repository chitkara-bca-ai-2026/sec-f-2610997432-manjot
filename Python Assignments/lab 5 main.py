import math
print("========================================")
print("       ENGINEERING CALCULATION TOOL")
print("========================================")
value = float(input("Enter a numerical value: "))
exponent = float(input("Enter an exponent: "))
power_val = math.pow(value, exponent)
sqrt_val = math.sqrt(value)
decimal_measurement = float(input("Enter a decimal measurement: "))
ceil_val = math.ceil(decimal_measurement)
floor_val = math.floor(decimal_measurement)
print("\n--- Results ---")
print(f"Value            : {value}")
print(f"Exponent         : {exponent}")
print(f"Power (pow)      : {power_val}")
print(f"Square Root (sqrt) : {sqrt_val:.4f}")
print(f"Decimal Value    : {decimal_measurement}")
print(f"Ceil Value       : {ceil_val}")
print(f"Floor Value      : {floor_val}")
print("========================================")
